-- N-Questie M2 Stage A2: nq-m2-effective v2 export pipeline.
--
-- Called by cli/validate-335.lua (NQ_EXPORT_SCHEMA_VERSION=2 +
-- NQ_EXPORT_V2_OUT) only after compile and all M0 checks passed. Order:
--   1. build every record (EffectiveExportV2.BuildAll, fails closed)
--   2. assemble the document and validate it (EffectiveSchemaV2.Validate)
--   3. serialise deterministically (EffectiveExportV2.Serialise)
--   4. parse the TEXT back with the safe literal parser (InputSchema), validate
--      it again and require it to equal the in-memory document
--   5. round trip on the PARSED records: rebuild, recompute positions and
--      compare with a fresh read of the compiled data; v1 equivalence for
--      SUPPORTED quests; M1 parity. Any difference fails
--   6. only then write, through SafeWrite (no-clobber, owner-only, no
--      symlinks); never with force
--   7. re-read the written file, require byte equality, parse and validate
-- A failure in steps 1-6 leaves no output file (nothing was installed).
-- A failure in step 7 means the installed file changed after SafeWrite's own
-- post-install check; it is reported and left in place for inspection (it is
-- no longer known to be ours, so it is not deleted).
-- No fsync is performed: the file is durable only as far as the filesystem
-- makes it; no power-loss guarantee is claimed.
-- Lua 5.1 compatible. Linux + GNU coreutils (via SafeWrite).

local V1 = dofile("tools/validation/EffectiveExport.lua")
local V2 = dofile("tools/validation/EffectiveExportV2.lua")
local Schema = dofile("tools/validation/EffectiveSchemaV2.lua")
local RT = dofile("tools/validation/RoundTripV2.lua")
local Input = dofile("tools/validation/InputSchema.lua")

local M = {}
M.HEADER = "N-Questie structural Questie records (nq-m2-effective v2). Generated by\n" ..
    "cli/validate-335.lua after all M0 checks passed. Public Questie data only.\n" ..
    "No display text, spawn coordinates or trigger-end contents (displayScope)."

local function readAll(path)
    local f = io.open(path, "rb")
    if not f then return nil end
    local s = f:read("*a")
    f:close()
    return s
end

-- Parse and validate exported text. Returns doc or nil, errors.
function M.ParseAndValidate(text, opts)
    opts = opts or {}
    if type(text) ~= "string" then return nil, { "v2 export: no text" } end
    if #text > Input.MAX_BYTES then return nil, { "v2 export: output larger than the reader limit (" .. Input.MAX_BYTES .. " bytes)" } end
    local doc, perr = Input.ParseString(text)
    if not doc then return nil, perr end
    local ok, verr = Schema.Validate(doc)
    if not ok then return nil, verr end
    local p = doc.provenance
    if p.dataKind ~= "effective" then return nil, { "v2 export: provenance.dataKind must be effective" } end
    if opts.expectCorrectionCount and p.correctionCount ~= opts.expectCorrectionCount then
        return nil, { "v2 export: provenance.correctionCount differs from the expected count" }
    end
    if opts.expectHarnessVersion and p.harnessVersion ~= opts.expectHarnessVersion then
        return nil, { "v2 export: provenance.harnessVersion differs from the running harness" }
    end
    return doc
end

-- Round trip of PARSED records against the compiled data (spec section 10).
function M.CheckParsed(doc, query, ids, ctx)
    local results, byId = {}, {}
    for _, q in ipairs(doc.quests) do byId[q.ID] = q end
    for _, id in ipairs(ids) do
        local q = byId[id]
        if not q then
            results[#results + 1] = { id = id, buildError = { "quest missing from the exported document" }, diffs = {}, norm = {} }
        else
            local raw = RT.ReadRaw(query, id)
            local v1rec = V1.Record(query, id, ctx)
            if not raw then
                results[#results + 1] = { id = id, buildError = { "re-read failed (QUERY_FAILED)" }, diffs = {}, norm = {} }
            else
                results[#results + 1] = RT.CheckRecord(q, raw, ctx.killCreditFirst[id] == true, v1rec)
            end
        end
    end
    local a = RT.Aggregate(results)
    local errs = {}
    if #doc.quests ~= #ids then errs[#errs + 1] = "v2 export: document has " .. #doc.quests .. " quests, expected " .. #ids end
    if a.processed ~= #ids then errs[#errs + 1] = "v2 export: checked " .. a.processed .. " of " .. #ids end
    if a.buildErrors > 0 then errs[#errs + 1] = "v2 export: " .. a.buildErrors .. " quest(s) missing or unreadable" end
    if a.validateErrors > 0 then errs[#errs + 1] = "v2 export: " .. a.validateErrors .. " parsed record(s) invalid" end
    if a.unclassified > 0 then errs[#errs + 1] = "v2 export: unclassified quests" end
    if a.questsDiffering > 0 then errs[#errs + 1] = "v2 export: round trip: " .. a.questsDiffering .. " quest(s) differ from the compiled data" end
    if a.v1Differing > 0 then errs[#errs + 1] = "v2 export: " .. a.v1Differing .. " SUPPORTED quest(s) differ from v1" end
    if a.expectedM1Disagree > 0 then errs[#errs + 1] = "v2 export: m1 classification disagrees with ExpectedM1" end
    if a.supported + a.unsupported ~= #ids then errs[#errs + 1] = "v2 export: status counts do not sum to the ID count" end
    if #errs > 0 then return nil, errs, a end
    return a
end

-- args: query, ids (all compiled IDs), ctx { killCreditFirst }, provenance
-- (ExportProvenance.Collect result), out (absolute path), repoRoot,
-- expectCorrectionCount, expectHarnessVersion, preWrite (optional function
-- returning true or false, reason; called last before writing).
-- testHooks (tests only, never set by the CLI): mutateDocument(doc) before
-- validation; mutateText(text) -> text before parsing; writer (SafeWrite
-- replacement); writeOpts (extra SafeWrite opts such as hooks).
-- Returns true, info { final, bytes, aggregate } or false, errors.
function M.Export(args, testHooks)
    testHooks = testHooks or {}
    local okCtx, cerr = V2.CheckContext(args.ctx)
    if not okCtx then return false, { "v2 export: " .. tostring(cerr) } end
    if type(args.provenance) ~= "table" then return false, { "v2 export: provenance missing" } end
    local ids = {}
    for i, id in ipairs(args.ids or {}) do ids[i] = id end
    table.sort(ids)
    local records, berr = V2.BuildAll(args.query, ids, args.ctx)
    if not records then return false, berr end
    local doc = V2.BuildDocument(records, args.provenance)
    if testHooks.mutateDocument then testHooks.mutateDocument(doc) end
    local okv, verr = Schema.Validate(doc)
    if not okv then return false, verr end
    local okS, text = pcall(V2.Serialise, doc, M.HEADER)
    if not okS then return false, { "v2 export: " .. tostring(text) } end
    if testHooks.mutateText then text = testHooks.mutateText(text) end
    local opts = { expectCorrectionCount = args.expectCorrectionCount, expectHarnessVersion = args.expectHarnessVersion }
    local parsed, perr = M.ParseAndValidate(text, opts)
    if not parsed then return false, perr end
    if Schema.Canonical(parsed, {}) ~= Schema.Canonical(doc, {}) then
        return false, { "v2 export: parsed text differs from the in-memory document" }
    end
    local agg, rerr = M.CheckParsed(parsed, args.query, ids, args.ctx)
    if not agg then return false, rerr end

    if args.preWrite then
        local okp, why = args.preWrite()
        if not okp then return false, { "v2 export: " .. tostring(why) } end
    end
    local Writer = testHooks.writer or dofile("tools/validation/SafeWrite.lua")
    local wopts = { repoRoot = args.repoRoot }
    for k, v in pairs(testHooks.writeOpts or {}) do wopts[k] = v end
    wopts.force = nil -- v2 never replaces a file
    local wok, final = Writer.WriteFile(args.out, text, wopts)
    if not wok then return false, { "v2 export: " .. tostring(final) } end

    local back = readAll(final)
    if back ~= text then
        return false, { "v2 export: re-read of " .. final .. " differs from the serialised text (left for inspection)" }
    end
    local reparsed, rperr = M.ParseAndValidate(back, opts)
    if not reparsed then
        local e = { "v2 export: re-read of " .. final .. " failed validation (left for inspection)" }
        for _, x in ipairs(rperr) do e[#e + 1] = x end
        return false, e
    end
    return true, { final = final, bytes = #text, aggregate = agg, text = text }
end

return M
